function t(k){ const d=I18N[SES.settings.lang]||I18N.en; return d[k] || I18N.en[k] || I18N.ru[k] || k }
function applyLang(){
  document.documentElement.lang=SES.settings.lang;
  document.querySelectorAll('[data-i18n]').forEach(el=>{ el.textContent=t(el.dataset.i18n) });
  document.querySelectorAll('#langseg button').forEach(b=>b.classList.toggle('on', b.dataset.l===SES.settings.lang));
  document.querySelectorAll('.sw').forEach(b=>{ const sp=b.querySelector('span'); if(sp) sp.textContent=t('th_'+b.dataset.t) });
  const lbl=(id,k)=>{ const el=$(id); if(!el) return; el.title=t(k); el.setAttribute('aria-label',t(k)) };
  lbl('statsBtn','stats'); lbl('setBtn','settings'); lbl('backBtn','backT'); lbl('rulesBtn','rulesT');
  const g=cur(); lbl('pauseBtn', g&&g.paused? 'resume':'pauseT');
  if(typeof renderHome==='function' && !$('home').classList.contains('hidden')) renderHome();
  if(document.body.classList.contains('won')) renderWinPanel();
}
